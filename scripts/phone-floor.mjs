// Writes the "phone floor" block of public/workspace/restrained.css (Release A, D02/D03/D05).
// Essential supporting text stays at 12px or more on phones (brief section 4). Rather than hunt down hundreds of small
// sizes by hand across the older sheets, this reads every sheet the workspace and the account pages load, finds each
// selector whose final size on a phone is under 12px, and repeats it in a phone-only media query with 12px.
// Bottom navigation labels (11px by design), avatar initials, count bubbles and the month-calendar chips are left alone.
// Two blocks: one for phones in general (up to 760px) and one for the narrowest phones (up to 380px), because a few
// older rules shrink text again below 360px.
// Run:  node scripts/phone-floor.mjs      (rewrites the block between the two marker comments)
import fs from "node:fs";
import path from "node:path";

const WS = path.join(process.cwd(), "public/workspace");
const SOURCES = [
  path.join(process.cwd(), "src/app/(site)/premium.css"),
  ...["styles", "product", "refinements", "home", "pulse", "directions", "polish", "feedback", "hub", "sandbox", "final", "calm"].map((n) => path.join(WS, `${n}.css`)),
  path.join(process.cwd(), "src/app/(account)/account.css"),
  path.join(WS, "restrained.css"),
];
const SKIP_SELECTOR = /\.mobile-nav|\.avatar|\.nav-count|\.mobile-badge|\.mobile-dot|\.nav-dot|\.notification-dot|\.cal-chip|\.month-day|kbd|::|:root|\bsvg\b/;
const FIELD = /(^|[\s>+~(,])(input|select|textarea)\b|\[type=/;
const esc = (x) => x.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const MARK_A = "/* >>> phone floor (generated by scripts/phone-floor.mjs; do not edit by hand) */";
const MARK_B = "/* <<< phone floor */";
const BLOCK = new RegExp(`${esc(MARK_A)}[\\s\\S]*?${esc(MARK_B)}`);

// Flat list of {selector, body, width}: width is the smallest max-width of an enclosing media query (Infinity for none).
// Rules that only apply to wide screens are left out.
function rules(css) {
  const out = [];
  const walk = (text, width, live) => {
    let i = 0;
    while (i < text.length) {
      const open = text.indexOf("{", i);
      if (open < 0) break;
      const head = text.slice(i, open).trim();
      let depth = 1, j = open + 1;
      while (j < text.length && depth) { const c = text[j]; if (c === "{") depth++; else if (c === "}") depth--; j++; }
      const body = text.slice(open + 1, j - 1);
      if (head.startsWith("@media")) {
        const max = /max-width:\s*(\d+)px/.exec(head), min = /min-width:\s*(\d+)px/.exec(head);
        const ok = live && !(min && Number(min[1]) > 320) && (!max || Number(max[1]) >= 320);
        walk(body, max ? Math.min(width, Number(max[1])) : width, ok);
      } else if (!head.startsWith("@")) { if (live) out.push({ selector: head, body, width }); }
      i = j;
    }
  };
  walk(css, Infinity, true);
  return out;
}

// For each selector: the last size set for a 390px phone and for a 320px phone (later rules win).
const at390 = new Map(), at320 = new Map();
for (const file of SOURCES) {
  if (!fs.existsSync(file)) continue;
  const css = fs.readFileSync(file, "utf8").replace(BLOCK, "").replace(/\/\*[\s\S]*?\*\//g, "");
  for (const r of rules(css)) {
    const decls = [...r.body.matchAll(/(?:^|;)\s*font(?:-size)?:\s*([^;}]*)/g)].map((m) => m[1]);
    let size = null, important = false;
    for (const d of decls) {
      const px = /([\d.]+)px/.exec(d), rem = /([\d.]+)rem/.exec(d);
      const v = px ? Number(px[1]) : rem ? Number(rem[1]) * 14 : null;
      if (v != null) { size = v; important = /!important/.test(d); }
    }
    if (size == null) continue;
    for (const sel of r.selector.split(",").map((x) => x.trim()).filter(Boolean)) {
      if (r.width >= 390) at390.set(sel, { size, important });
      at320.set(sel, { size, important });
    }
  }
}
const wanted = ([sel, v]) => v.size < 12 && !SKIP_SELECTOR.test(sel) && !FIELD.test(sel);
const decl = (v) => `font-size:12px${v.important ? "!important" : ""}`;
const general = [...at390].filter(wanted).sort(([a], [b]) => a.localeCompare(b));
const narrow = [...at320].filter(wanted).filter(([sel, v]) => !at390.has(sel) || at390.get(sel).size !== v.size).sort(([a], [b]) => a.localeCompare(b));
const block = `${MARK_A}\n@media(max-width:760px){\n${general.map(([s, v]) => `${s}{${decl(v)}}`).join("\n")}\n}\n@media(max-width:380px){\n${narrow.map(([s, v]) => `${s}{${decl(v)}}`).join("\n")}\n}\n${MARK_B}`;
const target = path.join(WS, "restrained.css");
let css = fs.readFileSync(target, "utf8");
css = BLOCK.test(css) ? css.replace(BLOCK, () => block) : `${css.trimEnd()}\n\n${block}\n`;
fs.writeFileSync(target, css);
console.log(`${general.length} selectors raised to 12px on phones, ${narrow.length} more on the narrowest`);
