#!/usr/bin/env python3
"""Second contrast pass for the 14th version (calmer colours).

The calmer grounds in public/workspace/calm.css moved some small muted text from just above to just
below the 4.5 : 1 line, and a sweep of every demo screen and pop-up (desktop and phone, axe
"color-contrast", saved as docs/psyalliance-v14/contrast_findings_v14.json) found other muted greens
that the first pass (make-contrast-css.py, version 13) never reached. For each failing text colour this
works out the same hue, darkened until it passes on the darkest background it sat on, finds every rule
in the workspace sheets that sets that colour, and writes the same selector again with the passing colour
between the markers at the end of calm.css. Nothing else changes. Run from the repo root:

    python3 e2e/tools/make-contrast-css-v14.py
"""
import colorsys, json, re, sys
SHEETS = ["styles", "product", "refinements", "home", "pulse", "directions", "polish", "feedback", "hub", "final", "calm"]
START, END = "/* contrast-v14:start */", "/* contrast-v14:end */"

def lum(h):
    h = h.lstrip("#"); r, g, b = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    f = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)
def ratio(a, b):
    la, lb = lum(a), lum(b)
    if la < lb: la, lb = lb, la
    return (la + 0.05) / (lb + 0.05)
def darken(src, bgs, need=4.7):
    h = src.lstrip("#"); r, g, b = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    hh, ll, ss = colorsys.rgb_to_hls(r, g, b)
    while ll > 0.05:
        ll -= 0.004
        rr, gg, bb = colorsys.hls_to_rgb(hh, ll, ss)
        c = "#%02x%02x%02x" % (round(rr * 255), round(gg * 255), round(bb * 255))
        if all(ratio(c, x) >= need for x in bgs): return c
    return src

found = json.load(open("docs/psyalliance-v14/contrast_findings_v14.json"))
by = {}
for f in found:
    if f.get("fg") and f.get("bg") and f["fg"].startswith("#") and f["bg"].startswith("#") and len(f["fg"]) == 7 and len(f["bg"]) == 7:
        by.setdefault(f["fg"].lower(), set()).add(f["bg"].lower())
fix = {s: darken(s, bgs) for s, bgs in by.items()}
fix = {s: d for s, d in fix.items() if d != s}

def walk(css):
    out = []
    def scan(text, prefix):
        k, m = 0, len(text)
        while k < m:
            o = text.find("{", k)
            if o < 0: break
            head = text[k:o].strip(); depth, j = 1, o + 1
            while j < m and depth:
                if text[j] == "{": depth += 1
                elif text[j] == "}": depth -= 1
                j += 1
            body = text[o + 1:j - 1]
            if head.startswith("@media") or head.startswith("@supports"): scan(body, head)
            elif not head.startswith("@"): out.append((prefix, head, body))
            k = j
    scan(css, ""); return out

rules, seen = [], set()
for name in SHEETS:
    css = open(f"public/workspace/{name}.css").read()
    if name == "calm" and START in css: css = css.split(START)[0]
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    for prefix, sel, body in walk(css):
        m = re.search(r"(?:^|;)\s*color\s*:\s*(#[0-9a-fA-F]{6})\b", body)
        if m and m.group(1).lower() in fix:
            key = (prefix, sel, fix[m.group(1).lower()])
            if key not in seen: seen.add(key); rules.append(key)
lines = [START, "/* Contrast, second pass (version 14). Generated by e2e/tools/make-contrast-css-v14.py from docs/psyalliance-v14/contrast_findings_v14.json. */"]
for prefix, sel, col in rules:
    lines.append(f"{prefix}{{{sel}{{color:{col}}}}}" if prefix else f"{sel}{{color:{col}}}")
lines.append(END)
block = "\n".join(lines)
p = "public/workspace/calm.css"; css = open(p).read()
if START in css: css = css.split(START)[0].rstrip() + "\n"
open(p, "w").write(css.rstrip() + "\n\n" + block + "\n")
sys.stderr.write(f"{len(fix)} colours mapped, {len(rules)} rules written\n")
for s, d in sorted(fix.items()): sys.stderr.write(f"  {s} -> {d}\n")
