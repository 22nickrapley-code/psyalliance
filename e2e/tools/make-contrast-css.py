#!/usr/bin/env python3
"""Builds the contrast section of public/workspace/final.css (decision D-04).

Reads the findings (docs/psyalliance-v13-parity/a11y_contrast_findings.csv) and the
frozen stylesheets, and for every rule in the frozen sheets that sets a failing
text colour writes the same selector again with the passing colour. The frozen
sheets are not touched; final.css loads after them. Run from the repo root:

    python3 e2e/tools/make-contrast-css.py > /tmp/contrast.css
"""
import csv, glob, re, sys, os

FINDINGS = "docs/psyalliance-v13-parity/a11y_contrast_findings.csv"
SHEETS = ["styles", "product", "refinements", "home", "pulse", "directions", "polish", "feedback", "hub"]

def lum(h):
    h = h.lstrip("#")
    r, g, b = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    f = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)

def ratio(a, b):
    la, lb = lum(a), lum(b)
    if la < lb: la, lb = lb, la
    return (la + 0.05) / (lb + 0.05)

# failing text colour -> the darkest passing colour listed for it
fix = {}
for r in csv.DictReader(open(FINDINGS)):
    src, dst = r["text_colour"].lower(), r["closest_passing_text_colour"].lower()
    if not dst or src == "#ffffff":
        continue
    if src not in fix or lum(dst) < lum(fix[src]):
        fix[src] = dst

def walk(css):
    """Yield (at_rule_prefix, selector, body) for every style rule, one level of @media deep."""
    i, n = 0, len(css)
    def block(start):
        depth, j = 1, start
        while j < n and depth:
            if css[j] == "{": depth += 1
            elif css[j] == "}": depth -= 1
            j += 1
        return j
    out = []
    def scan(text, prefix):
        k, m = 0, len(text)
        while k < m:
            o = text.find("{", k)
            if o < 0: break
            head = text[k:o].strip()
            depth, j = 1, o + 1
            while j < m and depth:
                if text[j] == "{": depth += 1
                elif text[j] == "}": depth -= 1
                j += 1
            body = text[o + 1:j - 1]
            if head.startswith("@media") or head.startswith("@supports"):
                scan(body, head)
            elif not head.startswith("@"):
                out.append((prefix, head, body))
            k = j
    scan(css, "")
    return out

rules = []
for name in SHEETS:
    css = open(f"public/workspace/{name}.css").read()
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    for prefix, sel, body in walk(css):
        m = re.search(r"(?:^|;)\s*color\s*:\s*(#[0-9a-fA-F]{6})\b", body)
        if m and m.group(1).lower() in fix:
            rules.append((prefix, sel, fix[m.group(1).lower()]))

# a rule repeated at the same place with the same colour once is enough
seen, out = set(), []
for prefix, sel, col in rules:
    key = (prefix, sel, col)
    if key in seen: continue
    seen.add(key)
    out.append((prefix, sel, col))

lines = ["/* Contrast (decision D-04, exception EXC-32). Generated by e2e/tools/make-contrast-css.py from the findings sheet. Small muted text moves to the passing colour of the same hue; nothing else changes. */"]
for prefix, sel, col in out:
    lines.append(f"{prefix}{{{sel}{{color:{col}}}}}" if prefix else f"{sel}{{color:{col}}}")
print("\n".join(lines))
sys.stderr.write(f"{len(fix)} colours mapped, {len(out)} rules written\n")
