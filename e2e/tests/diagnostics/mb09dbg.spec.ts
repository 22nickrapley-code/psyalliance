import { test, expect } from "@playwright/test";
import { signInAs, account } from "../../lib/auth";
import { assertLocal, q, asMember } from "../../lib/staging";
const avery = account("avery").id, bram = account("bram").id;
test.beforeEach(({ baseURL }) => assertLocal(baseURL!));
for (let i = 0; i < 4; i++) test(`mb09dbg ${i}`, async ({ browser, baseURL }) => {
  await q(`delete from workspace_drafts where profile_id = any($1::uuid[])`, [[avery, bram]]);
  await q(`delete from conversations where id in (select conversation_id from conversation_participants where profile_id = any($1::uuid[]))`, [[avery, bram]]);
  await q(`delete from referral_requests where requesting_profile_id = $1 and client_request_id is not null`, [avery]);
  await q(`delete from notification_events where dedup_key like 'message:%' or dedup_key like 'referral%'`);
  await q(`delete from notification_deliveries where recipient_profile_id = $1`, [avery]);
  const ref = (await asMember(avery, `select public.referral_create($1::jsonb) as r`, [JSON.stringify({ requestId: crypto.randomUUID(), focus: "Anxiety/Panic Disorders", secondary: "", state: "NY", city: "", age: "", setting: "virtual", insurance: "", language: "", prescribing: false, audience: "selected", selected: [bram], timeframe: "Within two weeks", message: "Evenings if possible." })])).rows[0].r;
  const bc = await browser.newContext({ viewport: { width: 1365, height: 900 } });
  await signInAs(bc, "bram", baseURL!);
  const b = await bc.newPage();
  await b.goto(`/dashboard/referrals?referral=${ref.referralId}`);
  await b.getByRole("button", { name: "Discuss first" }).click();
  await b.locator("#question-text").fill("Which evenings suit you?");
  await b.getByRole("button", { name: "Send question" }).click();
  await expect(b.locator("#toast")).toContainText("Your question is in");
  await bc.close();
  const ev = await q(`select e.id, e.event_type, e.summary, e.deep_link, e.dedup_key, d.channel from notification_events e join notification_deliveries d on d.notification_event_id = e.id where d.recipient_profile_id = $1 order by e.id`, [avery]);
  console.log("EVENTS " + i + " " + JSON.stringify(ev));
  const ac = await browser.newContext({ viewport: { width: 1365, height: 900 } });
  await signInAs(ac, "avery", baseURL!);
  const a = await ac.newPage();
  await a.goto("/dashboard/notifications");
  await a.waitForTimeout(800);
  const rows = await a.locator("li, article, .notification, .notice-row").filter({ has: a.getByRole("button", { name: "Open" }) }).evaluateAll((els) => els.map((e) => (e as HTMLElement).innerText.replace(/\s+/g, " ").slice(0, 120)));
  console.log("ROWS " + i + " " + JSON.stringify(rows));
  await ac.close();
});
